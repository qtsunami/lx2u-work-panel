import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The browser still receives one dependency-free loader. Only src/client/main.js
// and src/shared/*.js are editable sources; root client.js is checked-in output.
const root = new URL('../', import.meta.url);
const clientPath = fileURLToPath(new URL('client.js', root));
const templatePath = new URL('src/client/main.js', root);
const modules = ['workspace-sync.js', 'radar.js', 'auto-report.js', 'search.js', 'recommendations.js', 'report-preferences.js', 'quick-date.js'];

function embed(current, file) {
  // Every listed module is required. A missing file fails instead of silently
  // shipping an older generated region or a client without a capability.
  const source = readFileSync(new URL('src/shared/' + file, root), 'utf8');
  if (/^\s*(import|require)\s/m.test(source) || /\brequire\s*\(/.test(source)) {
    throw new Error(file + ' must remain self-contained browser-safe source (no imports)');
  }
  if (/\b(window|document|localStorage|process)\s*\./.test(source)) {
    throw new Error(file + ' must not reference browser or Node globals');
  }
  const key = file.replace(/\.js$/, '');
  const start = '    // @generated ' + key + ' begin';
  const end = '    // @generated ' + key + ' end';
  const first = current.indexOf(start), last = current.indexOf(end);
  if (first < 0 || last < first || current.indexOf(start, first + 1) >= 0 || current.indexOf(end, last + 1) >= 0) {
    throw new Error('missing or duplicated generated region for ' + file);
  }
  const body = source.replace(/^export\s+/gm, '').trimEnd()
    .split('\n').map((line) => line ? '    ' + line : '').join('\n');
  return current.slice(0, first) + start + '\n'
    + '    // Generated from src/shared/' + file + ' by scripts/build-client.mjs; do not edit this region.\n'
    + body + '\n' + current.slice(last);
}

let next = readFileSync(templatePath, 'utf8');
for (const file of modules) next = embed(next, file);
next = '// Generated by scripts/build-client.mjs from src/client/main.js and src/shared/*.js. DO NOT EDIT.\n' + next;
if (process.argv.includes('--check')) {
  if (next !== readFileSync(clientPath, 'utf8')) {
    throw new Error('Generated client.js is stale. Run: npm run build:client');
  }
  console.log('CLIENT BUILD PARITY OK (' + modules.length + ' required modules)');
} else {
  writeFileSync(clientPath, next, 'utf8');
  console.log('Built client.js from source (' + modules.length + ' modules)');
}
